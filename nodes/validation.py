"""Validate generated recipes against a pinned upstream Spack inside a container.

The validation sandbox reproduces the pattern of
``my-spack-envs/containerized/ubuntu2404.pdi-tutorial``: the recipes written
under ``outputs/`` are staged into a small Spack repository (the
``custom_packages/`` equivalent), which is then mounted read-only into a
throwaway container based on a pinned official Spack image. That image bundles
the upstream ``spack-packages`` snapshot, so every run validates against a
fresh upstream, and ``--rm`` keeps all side effects (installs, caches,
configuration) inside the sandbox.
"""

import shutil
import subprocess
from pathlib import Path

from state import AgentState

VALIDATION_IMAGE = "spack-it-2-validator"
VALIDATION_DIR = Path("validation")
GENERATED_NAMESPACE = "generated"

# Highest tier executed by validation/validate.sh. Tier 3 (spack install) is
# deliberately not wired yet.
MAX_TIER = "concretize"

# Exit codes returned by validation/validate.sh.
EXIT_VALIDATED = 0
EXIT_SANDBOX_FAILURE = 2
EXIT_AUDIT_FAILED = 10
EXIT_CONCRETIZE_FAILED = 20

# Package API version of the generated repository. It must be supported by the
# Spack version pinned in validation/Dockerfile.
REPO_YAML = "repo:\n  namespace: 'generated'\n  api: v2.2\n"


def route_after_recipe_generation(state: AgentState) -> str:
    """Validate the whole batch once, from the top-level run.

    Recursive child runs also end at ``generate_recipe`` but must not trigger
    their own validation: the parent run stages every generated recipe and
    validates the full set at once.
    """
    if state.get("status") != "recipe generated":
        return "done"

    if state.get("dependency_path"):
        return "done"

    return "validate_recipe"


def validate_recipe(state: AgentState) -> dict:
    """Stage and validate the recipes generated by this run."""
    recipe_model = state.get("recipe_model") or {}
    root_package = recipe_model.get("package_name")

    if not root_package:
        return _validation_failed_state(
            state, errors=["recipe model missing a package name"]
        )

    staged_packages = sorted(
        {root_package, *state.get("processed_packages", [])}
    )

    try:
        _stage_generated_repo(staged_packages)
        result = _run_validation_container(root_package)
    except _ValidationError as error:
        return _validation_failed_state(state, errors=[str(error)])

    tiers = _tier_results(result.returncode)
    status = _validation_status(result.returncode)

    validation = {
        "package": root_package,
        "staged_packages": staged_packages,
        "max_tier": MAX_TIER,
        "exit_code": result.returncode,
        "tiers": tiers,
        "log": (result.stdout + result.stderr).strip(),
    }

    if status == "recipe validated":
        return {
            "validation": validation,
            "current_stage": "validate_recipe",
            "status": status,
        }

    return _validation_failed_state(state, validation=validation)


def route_after_validation(state: AgentState) -> str:
    """Route according to the validation outcome."""
    if state.get("status") == "recipe validated":
        return "validated"

    return "validation_failed"


def validation_failed(state: AgentState) -> dict:
    """Stop when the generated recipes do not pass Spack validation."""
    return {
        "current_stage": "validation_failed",
        "status": "validation failed",
        "needs_human": True,
    }


class _ValidationError(RuntimeError):
    """Raised when the validation sandbox cannot be run."""


def _validation_failed_state(
    state: AgentState,
    validation: dict | None = None,
    errors: list[str] | None = None,
) -> dict:
    """Build the state update for a validation that could not pass."""
    update = {
        "current_stage": "validate_recipe",
        "status": "validation failed",
        "needs_human": True,
    }

    if validation is not None:
        update["validation"] = validation

    if errors:
        update["errors"] = state.get("errors", []) + errors

    return update


def _stage_generated_repo(packages: list[str]) -> None:
    """Copy the generated recipes into a fresh Spack repository layout."""
    repo_root = (
        VALIDATION_DIR / "generated" / "spack_repo" / GENERATED_NAMESPACE
    )

    if repo_root.exists():
        shutil.rmtree(repo_root)

    packages_dir = repo_root / "packages"
    packages_dir.mkdir(parents=True)
    (repo_root / "repo.yaml").write_text(REPO_YAML, encoding="utf-8")

    for package in packages:
        # Package API v2.x names package directories as Python modules.
        package_dir = package.replace("-", "_")
        source = Path("outputs") / package_dir / "package.py"

        if not source.is_file():
            raise _ValidationError(f"missing generated recipe: {source}")

        destination = packages_dir / package_dir
        destination.mkdir()
        shutil.copy2(source, destination / "package.py")


def _run_validation_container(
    root_package: str,
) -> subprocess.CompletedProcess:
    """Run the tiered validation inside a throwaway container."""
    generated_dir = (VALIDATION_DIR / "generated").resolve()

    try:
        _build_validation_image()
        return subprocess.run(
            [
                "docker",
                "run",
                "--rm",
                "--network",
                "none",
                "-v",
                f"{generated_dir}:/work/generated:ro",
                VALIDATION_IMAGE,
                f"{GENERATED_NAMESPACE}.{root_package}",
                MAX_TIER,
            ],
            capture_output=True,
            text=True,
            timeout=1800,
        )
    except FileNotFoundError as error:
        raise _ValidationError(
            "docker executable not found: the validation sandbox requires Docker"
        ) from error
    except subprocess.CalledProcessError as error:
        raise _ValidationError(
            "failed to build the validation image: "
            f"{(error.stderr or '').strip() or error}"
        ) from error
    except subprocess.TimeoutExpired as error:
        raise _ValidationError("validation timed out") from error


def _build_validation_image() -> None:
    """Build (or refresh from cache) the pinned validation image."""
    subprocess.run(
        ["docker", "build", "-q", "-t", VALIDATION_IMAGE, str(VALIDATION_DIR)],
        capture_output=True,
        text=True,
        check=True,
    )


def _validation_status(exit_code: int) -> str:
    """Classify the exit code returned by the validation sandbox."""
    if exit_code == EXIT_VALIDATED:
        return "recipe validated"

    if exit_code == EXIT_AUDIT_FAILED:
        return "audit findings"

    if exit_code == EXIT_CONCRETIZE_FAILED:
        return "concretization failed"

    return "validation sandbox failure"


def _tier_results(exit_code: int) -> dict:
    """Report the outcome of each executed tier."""
    if exit_code == EXIT_VALIDATED:
        return {"audit": "passed", "concretize": "passed"}

    if exit_code == EXIT_AUDIT_FAILED:
        return {"audit": "failed", "concretize": "skipped"}

    if exit_code == EXIT_CONCRETIZE_FAILED:
        return {"audit": "passed", "concretize": "failed"}

    if exit_code == EXIT_SANDBOX_FAILURE:
        return {"audit": "sandbox failure", "concretize": "skipped"}

    return {"audit": "sandbox failure", "concretize": "sandbox failure"}
